def hagoromo():
    c = Cv()
    for i in range(30):
        x = 1 + i
        y = 20 - 9 * math.sin(i / 29 * math.pi * 1.2) + 3 * math.sin(i * 0.5)
        for k in range(4):
            ch = 'W' if k == 0 else ('w' if k < 3 else 'v')
            put(c, x, int(round(y)) + k, ch)
        y2 = y + 7 + 2 * math.sin(i * 0.4 + 1)
        if 4 < i < 27:
            for k in range(2):
                put(c, x, int(round(y2)) + k, 'A' if k == 0 else 'a')
    for x, y in ((6, 6), (25, 25), (15, 3)):
        c.g(x - 1, y - 1, ".A.\nAWA\n.A.")
    return c


def onryo_haar():
    c = Cv()
    c.form(R(7, 3, 24, 6), 'qrR', 1, 1)
    c.g(8, 4, "Y.......Y.......")
    for k in range(9):
        x0 = 8 + k * 2
        for y in range(7, 29):
            x = x0 + int(round(math.sin(y * 0.35 + k * 0.9) * 1.5 + (y - 7) * (k - 4) * 0.06))
            ch = 'H' if (y + k) % 7 == 0 else ('h' if k % 2 else 'k')
            put(c, x, y, ch)
            if y < 26:
                put(c, x + 1, y, 'k')
    return c


