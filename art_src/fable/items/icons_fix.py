from ihelp import *


def put(c, x, y, ch):
    if 0 <= x < c.w and 0 <= y < c.h:
        c.a[y, x] = ch


def shimenawa():
    c = Cv()
    for x in range(3, 29):
        sag = int(round(2.2 * math.sin((x - 3) / 25 * math.pi)))
        for k in range(6):
            y = 8 + sag + k
            ph = (x + k) % 5
            ch = 's' if ph == 0 else ('C' if ph < 3 else 'c')
            if k == 0:
                ch = 's' if ph < 3 else 'C'
            if k == 5:
                ch = 'c' if ph < 3 else 'd'
            put(c, x, y, ch)
    c.g(1, 8, ".c\ncC\ncs\ncC\n.c")
    c.g(29, 8, "c.\nCc\nsc\nCc\nc.")
    for x in (8, 15, 22):
        sag = int(round(2.2 * math.sin((x - 3) / 25 * math.pi)))
        c.g(x - 1, 14 + sag, "WW..\n.WW.\n..WW\n.WW.\nWW..\n.Wv.\n..vv")
    for x in (12, 19):
        sag = int(round(2.2 * math.sin((x - 3) / 25 * math.pi)))
        c.g(x, 14 + sag, "c\nc\nC\nc\nc")
    return c


def hanabi():
    c = Cv()
    ring = [('Y', 11), ('y', 8), ('W', 5)]
    for k in range(12):
        a = k * math.tau / 12
        for r in range(3, 12):
            x, y = 16 + math.cos(a) * r, 14 + math.sin(a) * r
            ch = 'e' if r > 8 else ('y' if r > 5 else 'Y')
            if k % 2 and r > 9:
                continue
            put(c, int(round(x)), int(round(y)), ch)
        x, y = 16 + math.cos(a) * 12.5, 14 + math.sin(a) * 12.5
        if k % 2 == 0:
            c.g(int(round(x)) - 1, int(round(y)) - 1, ".R.\nReR\n.R.")
    for k in range(12):
        a = k * math.tau / 12 + math.pi / 12
        x, y = 16 + math.cos(a) * 7, 14 + math.sin(a) * 7
        put(c, int(round(x)), int(round(y)), 'A')
    c.g(14, 12, ".W.\nWWW\n.W.")
    c.g(16, 25, "o\no\ng\no\no")
    return c


