"""Hochauflösende Pixel-Art: Figuren, Yokai und Boss-Körper.

Jede Figur wird auf einem 32er-Raster entworfen und mit Faktor k gerendert
(k=1 -> 32 px, Bosse z. B. k=2.4). Schattierung, Glanzlichter und ein
dunkler Umriss geben den Pixel-Art-Look.
"""
import math
import pygame

OUT = (22, 14, 26)


def sh(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c)


class Pen:
    def __init__(self, k=1.0, w=32, h=32):
        self.k = k
        self.s = pygame.Surface((max(1, int(w * k)), max(1, int(h * k))), pygame.SRCALPHA)

    def p(self, x, y):
        return (int(round(x * self.k)), int(round(y * self.k)))

    def r(self, v):
        return max(1, int(round(v * self.k)))

    def ell(self, col, cx, cy, rx, ry, shade=True, hl=True):
        k = self.k
        rect = pygame.Rect(0, 0, max(1, int(2 * rx * k)), max(1, int(2 * ry * k)))
        rect.center = self.p(cx, cy)
        if shade:
            pygame.draw.ellipse(self.s, sh(col, 0.62), rect)
            inner = rect.inflate(-max(1, int(rx * k * 0.22)), -max(1, int(ry * k * 0.22)))
            inner.move_ip(-max(1, int(k * 0.8)), -max(1, int(k * 0.8)))
            pygame.draw.ellipse(self.s, col, inner)
        else:
            pygame.draw.ellipse(self.s, col, rect)
        if hl and rx * k > 3:
            h = pygame.Rect(0, 0, max(1, int(rx * k * 0.6)), max(1, int(ry * k * 0.4)))
            h.center = self.p(cx - rx * 0.35, cy - ry * 0.45)
            pygame.draw.ellipse(self.s, sh(col, 1.28), h)

    def circ(self, col, cx, cy, r, shade=True, hl=True):
        self.ell(col, cx, cy, r, r, shade, hl)

    def poly(self, col, pts, shade=False):
        P = [self.p(x, y) for x, y in pts]
        if shade:
            pygame.draw.polygon(self.s, sh(col, 0.65), P)
            cx = sum(x for x, y in pts) / len(pts)
            cy = sum(y for x, y in pts) / len(pts)
            P2 = [self.p(cx + (x - cx) * 0.86 - 0.5, cy + (y - cy) * 0.86 - 0.5) for x, y in pts]
            pygame.draw.polygon(self.s, col, P2)
        else:
            pygame.draw.polygon(self.s, col, P)

    def line(self, col, a, b, w=1.0):
        pygame.draw.line(self.s, col, self.p(*a), self.p(*b), self.r(w))

    def lines(self, col, pts, w=1.0):
        pygame.draw.lines(self.s, col, False, [self.p(*q) for q in pts], self.r(w))

    def rect(self, col, x, y, w, h):
        pygame.draw.rect(self.s, col, (*self.p(x, y), self.r(w), self.r(h)))

    def dot(self, col, x, y, r=0.8):
        pygame.draw.circle(self.s, col, self.p(x, y), max(1, int(r * self.k)))

    def eye(self, x, y, r=1.6, iris=(30, 20, 30), white=(250, 250, 245), glint=True):
        self.circ(white, x, y, r, False, False)
        self.dot(iris, x + 0.2, y + 0.1, r * 0.6)
        if glint and r * self.k >= 2:
            self.dot((255, 255, 255), x - r * 0.25, y - r * 0.3, max(0.4, r * 0.22))

    def finish(self):
        s = self.s
        m = pygame.mask.from_surface(s)
        o = pygame.Surface(s.get_size(), pygame.SRCALPHA)
        ms = m.to_surface(setcolor=OUT + (255,), unsetcolor=(0, 0, 0, 0))
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            o.blit(ms, (dx, dy))
        o.blit(s, (0, 0))
        return o


