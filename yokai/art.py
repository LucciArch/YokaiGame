_cache = {}


def make(name, k=None):
    if k is None:
        k = PLAYER_K if name in PLAYERS else SIZE.get(name, DEFAULT_ENEMY_K)
    key = (name, round(k, 3))
    s = _cache.get(key)
    if s is None:
        # Raster um 4 Einheiten nach unten verschieben, damit Hörner/Ohren nicht abgeschnitten werden
        g = Pen(k, 34, 38)
        g.p = lambda x, y, _p=g: (int(round((x + 1) * _p.k)), int(round((y + 4) * _p.k)))
        ARTS[name](g)
        s = g.finish()
        bb = s.get_bounding_rect()
        if bb.w and bb.h:
            s = s.subsurface(bb).copy()
        _cache[key] = s
    return s


def draw_big(surf, name, x, y, k, flip=False, extra=None):
    """Großes Exemplar (z. B. Boss) zentriert auf (x, y) zeichnen."""
    s = make(name, k)
    if flip:
        s = pygame.transform.flip(s, True, False)
    surf.blit(s, (int(x - s.get_width() / 2), int(y - s.get_height() / 2)))
    return s
