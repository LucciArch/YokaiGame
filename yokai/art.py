def chibi(p, skin=SKIN, top=(240, 238, 230), bottom=(200, 50, 60), legs=True, arms_col=None, belt=None):
    """Grundkörper einer menschlichen Figur im Chibi-Stil (Kopf groß)."""
    if legs:
        p.rect(sh(bottom, 0.75), 11.5, 26, 3.5, 5)
        p.rect(sh(bottom, 0.75), 17, 26, 3.5, 5)
        p.rect((40, 30, 30), 11, 30, 4.5, 1.5)
        p.rect((40, 30, 30), 16.5, 30, 4.5, 1.5)
    p.poly(bottom, [(10, 21), (22, 21), (23.5, 28), (8.5, 28)], True)
    p.poly(top, [(10.5, 16), (21.5, 16), (22.5, 22.5), (9.5, 22.5)], True)
    ac = arms_col or top
    p.ell(ac, 8.5, 20, 2.2, 3.4)
    p.ell(ac, 23.5, 20, 2.2, 3.4)
    p.circ(skin, 8.5, 23.2, 1.4, False, False)
    p.circ(skin, 23.5, 23.2, 1.4, False, False)
    p.line(sh(top, 0.7), (16, 16.5), (13.5, 20.5), 0.8)
    p.line(sh(top, 0.7), (16, 16.5), (18.5, 20.5), 0.8)
    if belt:
        p.rect(belt, 10, 21, 12, 1.6)


def head(p, skin=SKIN, cx=16, cy=10.5, r=7.2):
    p.circ(skin, cx, cy, r)


def face(p, cx=16, cy=11.5, eye_col=(40, 30, 50), mouth=True, blush=True, r=1.5):
    p.eye(cx - 3, cy, r, eye_col)
    p.eye(cx + 3, cy, r, eye_col)
    if blush:
        p.dot((240, 150, 150), cx - 4.6, cy + 2.4, 0.9)
        p.dot((240, 150, 150), cx + 4.6, cy + 2.4, 0.9)
    if mouth:
        p.line((150, 70, 70), (cx - 0.8, cy + 3.4), (cx + 0.8, cy + 3.4), 0.7)


